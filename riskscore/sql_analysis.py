"""Run every query in sql/ with DuckDB and write the results to reports/sql_findings.md."""
from __future__ import annotations

from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
SQL_DIR = ROOT / "sql"
CLEAN_CSV = ROOT / "data" / "clean" / "credit_default.csv"
SCORES_CSV = ROOT / "reports" / "test_scores.csv"
OUT = ROOT / "reports" / "sql_findings.md"


def to_markdown(rel: duckdb.DuckDBPyRelation) -> str:
    cols = rel.columns
    rows = rel.fetchall()
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    con = duckdb.connect()
    con.execute(f"CREATE TABLE credit AS SELECT * FROM read_csv_auto('{CLEAN_CSV.as_posix()}')")
    if SCORES_CSV.exists():
        con.execute(f"CREATE TABLE scores AS SELECT * FROM read_csv_auto('{SCORES_CSV.as_posix()}')")

    parts = ["# SQL findings\n", "Generated by `python -m riskscore.sql_analysis` from the queries in `sql/`.\n"]
    for path in sorted(SQL_DIR.glob("*.sql")):
        query = path.read_text(encoding="utf-8")
        if "FROM scores" in query and not SCORES_CSV.exists():
            continue
        title = " ".join(line.lstrip("- ").strip() for line in query.splitlines() if line.startswith("--"))
        parts.append(f"## {path.stem}\n\n{title}\n\n{to_markdown(con.sql(query))}\n")
        print(f"ran {path.name}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
